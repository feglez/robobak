# --- 6. DISK SPACE CHECK ---

# Compare source used space against destination total size to warn the user
# before robocopy fails mid-copy with ERROR 112 (not enough space).
# We compare against total size (not free space) because /MIR makes the
# destination an exact copy of the source - extras on the destination are
# deleted during the process, freeing space. Robocopy deletes extras before
# copying new files within each directory, though with /MT:16 multiple
# directories are processed in parallel, so theoretically a large new file
# could be written before extras in other directories are deleted, causing
# a transient space shortage even if the final result would fit.
# Get-DriveSpace (robobak-lib.ps1) uses [System.IO.DriveInfo], which works
# reliably with all volume types including VeraCrypt-mounted drives.
$SourceDrive = Get-DriveSpace $SourceLetter
$DestDrive   = Get-DriveSpace $DestLetter
$SourceUsed  = $SourceDrive.TotalSize - $SourceDrive.TotalFreeSpace
$DestTotal   = $DestDrive.TotalSize

if ($SourceUsed -gt $DestTotal) {
    $usedGB  = [math]::Round($SourceUsed / 1GB, 2)
    $totalGB = [math]::Round($DestTotal / 1GB, 2)
    Write-Host ""
    Write-Host "=================================================================" -ForegroundColor DarkGray
    Write-Host "   WARNING: DESTINATION DRIVE IS TOO SMALL" -ForegroundColor Yellow
    Write-Host "=================================================================" -ForegroundColor DarkGray
    Write-Host ""
    Write-Host "   Source used space:        $usedGB GB" -ForegroundColor Yellow
    Write-Host "   Destination total space:  $totalGB GB" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "   The destination drive is not large enough to hold all the" -ForegroundColor Yellow
    Write-Host "   data from the source. If you continue, the backup will be" -ForegroundColor Yellow
    Write-Host "   incomplete - Robocopy will fail when the destination runs" -ForegroundColor Yellow
    Write-Host "   out of space." -ForegroundColor Yellow
    Write-Host ""
    Write-Host "=================================================================" -ForegroundColor DarkGray
    $spaceChoice = Read-Host "Type Y to continue anyway (incomplete backup), any other key to cancel"
    if ($spaceChoice -ne 'Y') {
        Remove-DryRunTempFiles
        Write-Host "Operation cancelled by user." -ForegroundColor DarkYellow
        Read-Host "Press Enter to continue..."
        exit
    }
}

